export type AppErrorCode = ErrorCode | ClientErrorCode;
export type ErrorKind = "server" | "client";
export type ErrorI18nKey<C extends AppErrorCode = AppErrorCode> = `errors.${C}`;

export interface ErrorMeta<C extends AppErrorCode = AppErrorCode> {
  readonly kind: ErrorKind;
  readonly http?: number;
  readonly retryable: boolean;
  readonly surface: string;
  readonly recovery: readonly RecoveryPattern[];
  readonly i18nKey: ErrorI18nKey<C>;
  readonly entries: readonly string[];
  readonly contexts?: readonly string[];
}


import type { CommentDTO } from "@agrorende/contracts/dto";
import { EntityTypeEnum } from "@agrorende/contracts/enums";
import type { Comment } from "@agrorende/db";
import { z } from "zod";

export type { CommentDTO };

/** Parents that carry a comment thread (PLT-10). */
export const CommentParentTypeEnum = EntityTypeEnum.extract(["FIELD_REPORT", "WORK_ORDER", "RENTAL", "ASSET"]);
export type CommentParentType = z.infer<typeof CommentParentTypeEnum>;

/** Comment as listed on a thread: the synced row plus the author's display name. */
export interface CommentThreadItem extends CommentDTO {
  readonly authorName: string | null;
}

export const CommentListQuerySchema = z.object({
  entityType: CommentParentTypeEnum,
  entityId: z.string().uuid(),
});
export type CommentListQuery = z.infer<typeof CommentListQuerySchema>;

/** `POST /comments` body; `id` is optional on the web and generated by the server when absent. */
export const CommentCreateInputSchema = z.object({
  id: z.string().uuid().optional(),
  entityType: CommentParentTypeEnum,
  entityId: z.string().uuid(),
  body: z.string().trim().min(1).max(4000),
});
export type CommentCreateInput = z.infer<typeof CommentCreateInputSchema>;

export function toCommentDto(doc: Comment): CommentDTO {
  return {
    id: doc._id,
    organizationId: doc.organizationId,
    syncVersion: String(doc.syncVersion),
    createdAt: doc.createdAt.toISOString(),
    updatedAt: doc.updatedAt.toISOString(),
    deletedAt: doc.deletedAt === null || doc.deletedAt === undefined ? null : doc.deletedAt.toISOString(),
    entityType: doc.entityType,
    entityId: doc.entityId,
    authorId: doc.authorId,
    body: doc.body,
  };
}

import math, os
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

MATA6="#2B8A3E"; MATA7="#237032"; TERRA="#E8590C"; G900="#1F2328"; WHITE="#FFFFFF"
def f(v): return f"{v:.2f}".rstrip("0").rstrip(".")
def pt(cx,cy,r,deg):
    a=math.radians(deg-90); return cx+r*math.cos(a), cy+r*math.sin(a)

def gear(cx=32,cy=32,R=22.5,r=18,hole=9.5,n=8,tip=8.5,root=13.5):
    d=[]
    step=360/n
    for i in range(n):
        a=i*step
        p1=pt(cx,cy,r,a-root); p2=pt(cx,cy,R,a-tip); p3=pt(cx,cy,R,a+tip); p4=pt(cx,cy,r,a+root)
        d.append(("M" if i==0 else "L")+f"{f(p1[0])} {f(p1[1])}")
        d.append(f"L{f(p2[0])} {f(p2[1])}")
        d.append(f"A{f(R)} {f(R)} 0 0 1 {f(p3[0])} {f(p3[1])}")
        d.append(f"L{f(p4[0])} {f(p4[1])}")
        n1=pt(cx,cy,r,a+step-root)
        d.append(f"A{f(r)} {f(r)} 0 0 1 {f(n1[0])} {f(n1[1])}")
    d.append("Z")
    # hole, counter-clockwise
    d.append(f"M{f(cx)} {f(cy-hole)}A{f(hole)} {f(hole)} 0 1 0 {f(cx)} {f(cy+hole)}A{f(hole)} {f(hole)} 0 1 0 {f(cx)} {f(cy-hole)}Z")
    return "".join(d)

GEAR=gear()
LEAF="M26.6 37.4C26.6 31 31 26.6 37.6 26.4C37.4 33 33 37.4 26.6 37.4Z"
VEIN="M27.6 36.4L33.8 30.2"

def mark_inner(fg=WHITE, accent=TERRA, vein=MATA6):
    return (f'<path fill="{fg}" fill-rule="evenodd" d="{GEAR}"/>'
            f'<path fill="{accent}" d="{LEAF}"/>'
            f'<path fill="none" stroke="{vein}" stroke-width="1.6" stroke-linecap="round" d="{VEIN}"/>')

def badge(rx=14):
    return f'<rect width="64" height="64" rx="{rx}" fill="{MATA6}"/>'+mark_inner()

# text outlines
ROOT=os.path.abspath(os.path.join(os.path.dirname(__file__),"..","..",".."))
font=TTFont(os.path.join(ROOT,"apps/site/src/fonts/Geist-Variable-latin.woff2"))
font=instantiateVariableFont(font,{"wght":700})
gs=font.getGlyphSet(); cmap=font.getBestCmap(); upm=font["head"].unitsPerEm
hmtx=font["hmtx"]
def word(text, size, x0, baseline, track=-0.02):
    s=size/upm; x=x0; out=[]
    for ch in text:
        g=cmap[ord(ch)]
        pen=SVGPathPen(gs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
        tp=TransformPen(pen,(s,0,0,-s,x,baseline))
        gs[g].draw(tp); out.append(pen.getCommands())
        x+=hmtx[g][0]*s + track*size
    return "".join(out), x

def horizontal(textA, textB, fname):
    size=40; baseline=45
    a,xa=word("Agro",size,78,baseline)
    b,xb=word("Rende",size,xa,baseline)
    w=math.ceil(xb+2)
    svg=(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} 64" width="{w}" height="64" role="img" aria-label="AgroRende">'
         f'{badge()}<path fill="{textA}" d="{a}"/><path fill="{textB}" d="{b}"/></svg>\n')
    open(fname,"w").write(svg); return w

out=os.path.join(ROOT,"packages/design-tokens/brand")+"/"

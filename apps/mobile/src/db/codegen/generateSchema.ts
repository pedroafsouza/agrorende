/**
 * Generates `src/db/mirror.generated.ts` from the contracts DTO schemas so the
 * mobile mirror tables always carry the API field names (ARCHITECTURE §7.1).
 *
 * Regenerate after a DTO change (from the repository root):
 *   npx tsx apps/mobile/src/db/codegen/generateSchema.ts
 *   npx tsx apps/mobile/src/db/codegen/generateMigrations.ts
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import * as dto from "@agrorende/contracts/dto";
import { TABLE_ORDER, type TableName } from "@agrorende/contracts/sync";

type ColumnKind = "text" | "integer" | "real" | "boolean" | "json";

const DTO_BY_TABLE: Record<TableName, string> = {
  organization: "OrganizationDTOSchema",
  users: "UserDTOSchema",
  sites: "SiteDTOSchema",
  plots: "PlotDTOSchema",
  seasons: "SeasonDTOSchema",
  customers: "CustomerDTOSchema",
  assets: "AssetDTOSchema",
  checklistTemplates: "ChecklistTemplateDTOSchema",
  damages: "DamageDTOSchema",
  fieldReports: "FieldReportDTOSchema",
  workOrders: "WorkOrderDTOSchema",
  workOrderParts: "WorkOrderPartDTOSchema",
  rentals: "RentalDTOSchema",
  rentalCharges: "RentalChargeDTOSchema",
  inspections: "InspectionDTOSchema",
  media: "MediaDTOSchema",
  activityEvents: "ActivityEventDTOSchema",
  notifications: "NotificationDTOSchema",
  comments: "CommentDTOSchema",
  parts: "PartDTOSchema",
  stockLocations: "StockLocationDTOSchema",
  stockLevels: "StockLevelDTOSchema",
  maintenancePlans: "MaintenancePlanDTOSchema",
  fuelLogs: "FuelLogDTOSchema",
};

interface ZodCheckLike {
  readonly kind?: string;
  readonly _zod?: { readonly def?: { readonly check?: string; readonly format?: string } };
}

interface ZodDefLike {
  readonly type?: string;
  readonly typeName?: string;
  readonly innerType?: ZodLike;
  readonly schema?: ZodLike;
  readonly checks?: readonly ZodCheckLike[];
  readonly getter?: () => ZodLike;
  readonly in?: ZodLike;
  readonly options?: readonly ZodLike[];
}

interface ZodLike {
  readonly _def: ZodDefLike;
  readonly shape?: Record<string, ZodLike>;
}

const WRAPPERS = new Set(["optional", "nullable", "default", "prefault", "catch", "readonly", "nonoptional", "branded"]);

function snake(name: string): string {
  return name.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
}

/** Supports zod v4 (`_def.type`) and v3 (`_def.typeName`) definitions. */
function typeOf(schema: ZodLike): string {
  const def = schema._def;
  if (def.type !== undefined) return def.type;
  return (def.typeName ?? "").replace(/^Zod/, "").toLowerCase();
}

function unwrap(schema: ZodLike): ZodLike {
  let current = schema;
  for (;;) {
    const type = typeOf(current);
    const def = current._def;
    if (WRAPPERS.has(type) && def.innerType !== undefined) {
      current = def.innerType;
    } else if (type === "effects" && def.schema !== undefined) {
      current = def.schema;
    } else if (type === "lazy" && def.getter !== undefined) {
      current = def.getter();
    } else if ((type === "pipe" || type === "pipeline") && def.in !== undefined) {
      current = def.in;
    } else {
      return current;
    }
  }
}

function isInteger(schema: ZodLike): boolean {
  return (schema._def.checks ?? []).some((check) => check.kind === "int" || ["safeint", "int32", "uint32"].includes(check._zod?.def?.format ?? ""));
}

function kindOf(field: string, schema: ZodLike): ColumnKind {
  if (field === "syncVersion") return "integer";
  const inner = unwrap(schema);
  switch (typeOf(inner)) {
    case "string":
    case "enum":
    case "nativeenum":
    case "literal":
    case "template_literal":
      return "text";
    case "number":
    case "int":
      return isInteger(inner) || typeOf(inner) === "int" ? "integer" : "real";
    case "boolean":
      return "boolean";
    case "union": {
      const kinds = new Set((inner._def.options ?? []).map((option) => kindOf(field, option)));
      const [only] = [...kinds];
      return kinds.size === 1 && only !== undefined ? only : "json";
    }
    default:
      return "json";
  }
}

function builderFor(field: string, kind: ColumnKind): string {
  const name = JSON.stringify(field);
  switch (kind) {
    case "integer":
      return `integer(${name})`;
    case "real":
      return `real(${name})`;
    case "boolean":
      return `integer(${name}, { mode: "boolean" })`;
    case "json":
      return `text(${name}, { mode: "json" })`;
    default:
      return `text(${name})`;
  }
}

let body = `// GENERATED by src/db/codegen/generateSchema.ts from the @agrorende/contracts DTOs. Do not edit.
import { index, integer, real, sqliteTable, text } from "drizzle-orm/sqlite-core";

`;
const meta: string[] = [];
for (const table of TABLE_ORDER) {
  const schemaName = DTO_BY_TABLE[table];
  const schema = (dto as unknown as Record<string, ZodLike | undefined>)[schemaName];
  if (schema?.shape === undefined) throw new Error(`missing DTO ${schemaName}`);
  const columns: string[] = [];
  const kinds: string[] = [];
  for (const [field, fieldSchema] of Object.entries(schema.shape)) {
    const kind = kindOf(field, fieldSchema);
    kinds.push(`${field}: "${kind}"`);
    columns.push(field === "id" ? `    id: text("id").primaryKey(),` : `    ${field}: ${builderFor(field, kind)},`);
  }
  columns.push(`    _dirty: integer("_dirty").notNull().default(0),`);
  body += `export const ${table} = sqliteTable(\n  "${snake(table)}",\n  {\n${columns.join("\n")}\n  },\n  (table) => [index("${snake(table)}_dirty_idx").on(table._dirty)],\n);\n\n`;
  meta.push(`  ${table}: { sqlName: "${snake(table)}", columns: { ${kinds.join(", ")} } },`);
}

body += `/** Column kinds per mirror table, used to encode DTO rows for SQLite and decode them back. */
export const MIRROR_TABLES = {
${meta.join("\n")}
} as const;
`;

const outFile = join(dirname(fileURLToPath(import.meta.url)), "..", "mirror.generated.ts");
writeFileSync(outFile, body);
process.stdout.write(`wrote ${outFile}\n`);

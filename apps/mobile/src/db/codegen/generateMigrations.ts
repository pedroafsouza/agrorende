/**
 * Bundles the drizzle-kit SQL migrations into `src/db/drizzle/migrations.ts`.
 *
 * drizzle-kit's `driver: "expo"` emits `migrations.js` importing `.sql` files, which
 * needs a Babel inline-import plugin. This script inlines the SQL as strings in the
 * same `{ journal, migrations }` shape that `useMigrations` and our runner accept.
 *
 *   cd apps/mobile && npx drizzle-kit generate --config src/db/drizzle.config.ts --name <name>
 *   npx tsx src/db/codegen/generateMigrations.ts
 */
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

interface JournalEntry {
  readonly idx: number;
  readonly when: number;
  readonly tag: string;
  readonly breakpoints: boolean;
}

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "drizzle");
const journal = JSON.parse(readFileSync(join(dir, "meta", "_journal.json"), "utf8")) as { entries: JournalEntry[] };

const lines = journal.entries.map((entry) => {
  const key = `m${String(entry.idx).padStart(4, "0")}`;
  const sql = readFileSync(join(dir, `${entry.tag}.sql`), "utf8");
  return `    ${key}: ${JSON.stringify(sql)},`;
});

const out = `// GENERATED by src/db/codegen/generateMigrations.ts from drizzle-kit output. Do not edit.
export const migrationBundle = {
  journal: ${JSON.stringify({ entries: journal.entries }, null, 2).replace(/\n/g, "\n  ")},
  migrations: {
${lines.join("\n")}
  } as Record<string, string>,
};
`;

writeFileSync(join(dir, "migrations.ts"), out);
const legacy = join(dir, "migrations.js");
if (existsSync(legacy)) rmSync(legacy);
process.stdout.write(`wrote ${join(dir, "migrations.ts")}\n`);

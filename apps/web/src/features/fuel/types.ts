import { fromZonedTime } from "date-fns-tz";

import { DEFAULT_TIME_ZONE } from "@/lib/format";

export type { FuelConsumptionDTO, FuelLogListItem } from "@agrorende/core/modules/fuel/dto";
export type { FuelLogDTO } from "@agrorende/contracts/dto";

export interface FuelFormValues {
  readonly assetId: string | null;
  readonly liters: string;
  readonly pricePerLiterCents: number | null;
  readonly hourMeter: string;
  readonly odometerKm: string;
  readonly siteId: string | null;
  /** `datetime-local` in the organisation timezone; empty means now. */
  readonly filledAt: string;
  readonly notes: string;
}

export const EMPTY_FUEL_FORM: FuelFormValues = {
  assetId: null,
  liters: "",
  pricePerLiterCents: null,
  hourMeter: "",
  odometerKm: "",
  siteId: null,
  filledAt: "",
  notes: "",
};

/** `1.234,5` or `1234.5` → 1234.5; null when empty or not a finite number. */
export function parseDecimal(text: string): number | null {
  const trimmed = text.trim().replace(/\s/gu, "");
  if (trimmed.length === 0) return null;
  const normalised = trimmed.includes(",") ? trimmed.replace(/\./gu, "").replace(",", ".") : trimmed;
  if (!/^\d+(\.\d+)?$/u.test(normalised)) return null;
  const value = Number(normalised);
  return Number.isFinite(value) ? value : null;
}

export type FuelFormErrors = Partial<Record<"assetId" | "liters" | "hourMeter" | "odometerKm", "required" | "invalid">>;

/** Client checks that mirror `FuelLogCreatePayloadSchema`: machine required, litres above zero, readings non-negative. */
export function validateFuelForm(values: FuelFormValues): FuelFormErrors {
  const errors: FuelFormErrors = {};
  if (values.assetId === null) errors.assetId = "required";
  const liters = parseDecimal(values.liters);
  if (values.liters.trim().length === 0) errors.liters = "required";
  else if (liters === null || liters <= 0) errors.liters = "invalid";
  if (values.hourMeter.trim().length > 0 && parseDecimal(values.hourMeter) === null) errors.hourMeter = "invalid";
  if (values.odometerKm.trim().length > 0 && parseDecimal(values.odometerKm) === null) errors.odometerKm = "invalid";
  return errors;
}

/** Body for `POST /fuel-logs`. The id is generated by the caller so a retried save stays one log. */
export function fuelBody(values: FuelFormValues, id: string, timeZone = DEFAULT_TIME_ZONE): Record<string, unknown> {
  const notes = values.notes.trim();
  const hourMeter = parseDecimal(values.hourMeter);
  const odometerKm = parseDecimal(values.odometerKm);
  const filledAt = values.filledAt.length === 0 ? null : fromZonedTime(values.filledAt, timeZone);
  return {
    id,
    assetId: values.assetId,
    liters: parseDecimal(values.liters),
    ...(values.pricePerLiterCents === null ? {} : { pricePerLiterCents: values.pricePerLiterCents }),
    ...(hourMeter === null ? {} : { hourMeter }),
    ...(odometerKm === null ? {} : { odometerKm }),
    ...(values.siteId === null ? {} : { siteId: values.siteId }),
    ...(filledAt === null || Number.isNaN(filledAt.getTime()) ? {} : { filledAt: filledAt.toISOString() }),
    media: [],
    ...(notes.length > 0 ? { notes } : {}),
  };
}

/** Total shown while typing: litres × price, rounded to whole cents, or null when either is missing. */
export function previewTotalCents(values: Pick<FuelFormValues, "liters" | "pricePerLiterCents">): number | null {
  const liters = parseDecimal(values.liters);
  if (liters === null || values.pricePerLiterCents === null) return null;
  return Math.round(liters * values.pricePerLiterCents);
}
